def holm(ps):
    ps = list(ps); order = sorted(range(len(ps)), key=lambda i: ps[i]); out = [0.0] * len(ps); run = 0.0
    for r, i in enumerate(order):
        run = max(run, min(1.0, (len(ps) - r) * ps[i])); out[i] = run
    return out


def wilson(x, n, z=1.959964):
    p = x / n; d = 1 + z * z / n; c = p + z * z / (2 * n); h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (c - h) / d, (c + h) / d


def check(where, claim, reported, getter, source, tol=None, note=""):
    """reported: value as printed (string); getter: callable returning the computed value."""
    try:
        val = getter()
    except Exception as e:  # noqa: BLE001
        RESULTS.append(dict(where=where, claim=claim, reported=reported, computed=f"ERROR {e}", source=source,
                            status="FAIL", note=note)); return
    if isinstance(val, bool) or isinstance(reported, bool):
        ok = bool(val) == bool(reported) if isinstance(reported, bool) else bool(val)
        shown = str(val)
    else:
        rep = str(reported).replace(",", "").replace("−", "-")
        dec = len(rep.split(".")[1]) if "." in rep else 0
        t = tol if tol is not None else 0.5 * 10 ** (-dec) + 1e-9
        ok = abs(float(val) - float(rep)) <= t
        shown = f"{float(val):.{max(dec, 1) + 2}f}" if not float(val).is_integer() else f"{int(val)}"
    RESULTS.append(dict(where=where, claim=claim, reported=reported, computed=shown, source=source,
                        status="PASS" if ok else "FAIL", note=note))


